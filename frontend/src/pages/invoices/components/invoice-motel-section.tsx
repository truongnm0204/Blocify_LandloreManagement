import { useState, useMemo } from 'react'
import { useNavigate } from 'react-router-dom'
import { Building2, ChevronLeft, ChevronRight } from 'lucide-react'
import type { Invoice, InvoiceStatus } from '@/types'

const SECTION_PAGE_SIZE = 10

const STATUS_CONFIG: Record<InvoiceStatus, { label: string; bg: string; text: string }> = {
  DRAFT: { label: 'Nhap', bg: 'bg-gray-100', text: 'text-gray-600' },
  ISSUED: { label: 'Da phat hanh', bg: 'bg-blue-50', text: 'text-blue-700' },
  PARTIALLY_PAID: { label: 'Thanh toan mot phan', bg: 'bg-yellow-50', text: 'text-yellow-700' },
  PAID: { label: 'Da thanh toan', bg: 'bg-green-50', text: 'text-green-700' },
  OVERDUE: { label: 'Qua han', bg: 'bg-red-50', text: 'text-red-700' },
}

function formatVnd(value: number): string {
  return value.toLocaleString('vi-VN') + ' d'
}

function formatDate(dateStr: string): string {
  try {
    return new Date(dateStr).toLocaleDateString('vi-VN')
  } catch {
    return dateStr
  }
}

function StatusBadge({ status }: { status: InvoiceStatus }) {
  const cfg = STATUS_CONFIG[status] ?? STATUS_CONFIG.DRAFT
  return (
    <span className={`inline-flex items-center rounded-full px-2.5 py-0.5 text-xs font-medium ${cfg.bg} ${cfg.text}`}>
      {cfg.label}
    </span>
  )
}

interface InvoiceMotelSectionProps {
  motelName: string
  invoices: Invoice[]
  hideHeader?: boolean
}

export function InvoiceMotelSection({ motelName, invoices, hideHeader }: InvoiceMotelSectionProps) {
  const navigate = useNavigate()
  const [page, setPage] = useState(1)

  const totalItems = invoices.length
  const totalPages = Math.ceil(totalItems / SECTION_PAGE_SIZE)

  const pagedInvoices = useMemo(() => {
    const start = (page - 1) * SECTION_PAGE_SIZE
    return invoices.slice(start, start + SECTION_PAGE_SIZE)
  }, [invoices, page])

  // Reset to page 1 if invoices change and current page is out of bounds
  if (page > totalPages && totalPages > 0) {
    setPage(1)
  }

  return (
    <div>
      {!hideHeader && (
        <div className="mb-2 flex items-center gap-2">
          <Building2 className="h-4 w-4 text-[#1d5fa8]" />
          <h4 className="text-sm font-semibold text-[#323235]">{motelName}</h4>
          <span className="rounded-full bg-[#e8f0fe] px-2 py-0.5 text-xs font-medium text-[#1d5fa8]">
            {totalItems} hoa don
          </span>
        </div>
      )}

      <div className="overflow-x-auto rounded-xl bg-white shadow-[0_1px_3.5px_rgba(0,0,0,0.05)]">
        <table className="w-full min-w-[800px]">
          <thead>
            <tr className="border-b border-gray-100 text-left text-xs font-medium uppercase text-[#7b7a7d]">
              <th className="px-5 py-3">Ma hoa don</th>
              <th className="px-5 py-3">Phong</th>
              <th className="px-5 py-3">Nguoi thue</th>
              <th className="px-5 py-3">Ky</th>
              <th className="px-5 py-3 text-right">Tong tien</th>
              <th className="px-5 py-3 text-right">Da tra</th>
              <th className="px-5 py-3">Trang thai</th>
              <th className="px-5 py-3">Han tra</th>
            </tr>
          </thead>
          <tbody>
            {pagedInvoices.map((inv) => (
              <tr
                key={inv.id}
                onClick={() => navigate(`/invoices/${inv.id}`)}
                className="cursor-pointer border-b border-gray-50 transition-colors last:border-0 hover:bg-gray-50"
              >
                <td className="px-5 py-4 text-sm font-medium text-[#1d5fa8] hover:underline">
                  {inv.invoiceCode}
                  {inv.autoGenerated && (
                    <span className="ml-1.5 rounded bg-blue-100 px-1.5 py-0.5 text-[10px] font-medium text-blue-700">
                      Tu dong
                    </span>
                  )}
                </td>
                <td className="px-5 py-4 text-sm text-[#323235]">
                  {inv.room?.roomCode ?? '—'}
                </td>
                <td className="px-5 py-4 text-sm text-[#323235]">
                  {inv.representativeTenant?.fullName ?? '—'}
                </td>
                <td className="px-5 py-4 text-sm text-[#7b7a7d]">
                  {inv.invoiceMonth}/{inv.invoiceYear}
                </td>
                <td className="px-5 py-4 text-right text-sm font-medium text-[#323235]">
                  {formatVnd(inv.totalAmount)}
                </td>
                <td className="px-5 py-4 text-right text-sm text-[#7b7a7d]">
                  {formatVnd(inv.paidAmount)}
                </td>
                <td className="px-5 py-4">
                  <StatusBadge status={inv.status} />
                </td>
                <td className="px-5 py-4 text-sm text-[#7b7a7d]">
                  {inv.dueDate ? formatDate(inv.dueDate) : '—'}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      {totalPages > 1 && (
        <div className="flex items-center justify-between px-1 py-3">
          <p className="text-sm text-[#7b7a7d]">
            Trang {page} / {totalPages} ({totalItems} hoa don)
          </p>
          <div className="flex items-center gap-1">
            <button
              onClick={() => setPage((p) => Math.max(1, p - 1))}
              disabled={page <= 1}
              className="rounded-lg p-1.5 text-[#7b7a7d] transition-colors hover:bg-gray-100 disabled:opacity-40"
            >
              <ChevronLeft className="h-4 w-4" />
            </button>
            {Array.from({ length: totalPages }, (_, i) => i + 1).map((p) => (
              <button
                key={p}
                onClick={() => setPage(p)}
                className={`min-w-[32px] rounded-lg px-2.5 py-1 text-sm font-medium transition-colors ${
                  p === page
                    ? 'bg-[#1d5fa8] text-white'
                    : 'text-[#7b7a7d] hover:bg-gray-100'
                }`}
              >
                {p}
              </button>
            ))}
            <button
              onClick={() => setPage((p) => Math.min(totalPages, p + 1))}
              disabled={page >= totalPages}
              className="rounded-lg p-1.5 text-[#7b7a7d] transition-colors hover:bg-gray-100 disabled:opacity-40"
            >
              <ChevronRight className="h-4 w-4" />
            </button>
          </div>
        </div>
      )}
    </div>
  )
}
